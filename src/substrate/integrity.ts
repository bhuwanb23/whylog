/**
 * The integrity stamp.
 *
 * Phase 0 · sub-phase 0.6, consumed by Phase 5
 * Plan: plan/phase-5-export-compiler.md §5.6
 *
 * ---------------------------------------------------------------------------
 * WHY AN EXPORTED FILE CARRIES A HASH
 *
 * `DECISIONS.md` and `CLAUDE.md` are read by an agent that cannot ask whether
 * they are current. A stale rule file is worse than none, because the agent
 * follows it confidently.
 *
 * So every export carries a stamp: the head hash of the log it was compiled from,
 * the counts it contained, and the compliance score at generation time. A CI check
 * (Phase 5.7) re-reads the file, compares the stamp against the current log, and
 * fails with a sentence rather than a mystery: "DECISIONS.md was generated from
 * log abc123… and the log is now at def456…; 4 decisions have changed since."
 *
 * This is the mechanism behind Richards & Ford's compliance section and the
 * fitness-function ADRs in docs/04 §7 — except those are all authored by hand.
 * Here the stamp is a byproduct of compiling, so it cannot be forgotten.
 * ---------------------------------------------------------------------------
 */

import { nowISO } from "@/lib/format";
import type { ISODateString } from "@/types/common";
import { isWorldObservable } from "@/types/domain";
import type { IntegrityStamp, StampVerification } from "@/types/export";
import type { GraphState } from "./graph-state";
import { GENESIS_HASH, linkHash } from "./hash-chain";
import { compliance, coverage, soundness } from "./projections/metrics";
import { SCHEMA_VERSION } from "./schema";

/**
 * Build the stamp for the current state.
 *
 * Pure apart from the timestamp, which the caller supplies in normal use; the
 * default is a convenience for the interactive export path.
 */
export function buildStamp(state: GraphState, at: ISODateString = nowISO()): IntegrityStamp {
  const report = compliance(state);
  const cov = coverage(state);
  const sound = soundness(state);

  let premisesContested = 0;
  let premisesIn = 0;
  let premisesOut = 0;

  for (const premise of state.premises.values()) {
    if (premise.label === "IN") premisesIn += 1;
    else if (premise.label === "OUT") premisesOut += 1;
    if (premise.temporal.invalidFrom !== undefined && premise.label === "UNKNOWN") {
      premisesContested += 1;
    }
  }

  let superseded = 0;
  for (const decision of state.decisions.values()) {
    if (decision.status === "superseded") superseded += 1;
  }

  return {
    headHash: state.headHash,
    generatedAt: at,
    schemaVersion: state.schemaVersion,
    decisions: {
      total: state.decisions.size,
      inLabel: sound.inLabel,
      out: sound.out,
      superseded,
    },
    premises: {
      total: state.premises.size,
      inLabel: premisesIn,
      out: premisesOut,
      contested: premisesContested,
    },
    compliance: report.compliance,
    verifiableCoverage: cov.verifiableCoverage,
    guards: { passing: report.passing, failing: report.failing },
    engineAtGeneration: describeEngine(state.engine),
  };
}

function describeEngine(engine: { kind: string; model: string }): string {
  return engine.model.length > 0 ? `${engine.kind}:${engine.model}` : engine.kind;
}

/**
 * Verify a stamp against the current log.
 *
 * Three failure modes, reported distinctly because they have different fixes:
 *   `head-mismatch`        the file is stale — recompile it
 *   `missing-stamp`        the file was hand-edited or predates stamping — recompile
 *   `schema-incompatible`  the file came from a build this one cannot read — update
 */
export function verifyStamp(
  stamp: IntegrityStamp | null | undefined,
  currentHeadHash: string,
): StampVerification {
  if (stamp === null || stamp === undefined) {
    return { ok: false, reason: "missing-stamp" };
  }
  if (stamp.schemaVersion > SCHEMA_VERSION) {
    return { ok: false, reason: "schema-incompatible", found: String(stamp.schemaVersion) };
  }
  if (stamp.headHash !== currentHeadHash) {
    return {
      ok: false,
      reason: "head-mismatch",
      expected: currentHeadHash,
      found: stamp.headHash,
    };
  }
  return { ok: true };
}

/** The sentence a CI job prints. Written for a person who has never seen WhyLog:
 *  it says what is wrong, how big the gap is, and what to do. */
export function describeVerification(
  verification: StampVerification,
  path: string,
  current: GraphState | null,
): string {
  if (verification.ok) return `${path} is current.`;

  switch (verification.reason) {
    case "missing-stamp":
      return `${path} carries no WhyLog integrity stamp. It was hand-edited or generated before stamping existed; recompile it from the log.`;

    case "schema-incompatible":
      return `${path} was generated by a WhyLog build using schema v${verification.found}; this build reads v${SCHEMA_VERSION}. Update and recompile.`;

    case "head-mismatch": {
      if (current === null) {
        return `${path} is stale: it was compiled from log ${verification.found?.slice(0, 12)}… and the log is now at ${verification.expected?.slice(0, 12)}….`;
      }
      const changed = countChangedSince(current, verification.found ?? "");
      return [
        `${path} is stale.`,
        `It was compiled from log ${verification.found?.slice(0, 12)}…; the log is now at ${verification.expected?.slice(0, 12)}….`,
        changed === null
          ? "The compiling event is no longer in the log."
          : `${changed} event${changed === 1 ? "" : "s"} have been recorded since.`,
        "Recompile to bring it up to date.",
      ].join(" ");
    }
  }
}

/** How many events were appended after a given head hash. Returns null when the
 *  hash is not an ancestor of the current head — which means the file came from a
 *  different chain entirely, not merely an older one. */
export function countChangedSince(state: GraphState, headHash: string): number | null {
  if (headHash.length === 0) return null;

  // Walking the chain backwards is not possible, so walk it forwards and find the
  // position at which the running hash equals the stamp's.
  // Recompute from genesis using the same link function the log uses.
  const { GENESIS_HASH: genesis, linkHash: link } = chainHelpers();
  let running: string = genesis;

  for (let i = 0; i < state.events.length; i += 1) {
    const event = state.events[i];
    if (!event) continue;
    running = link(running, event);
    if (running === headHash) return state.events.length - (i + 1);
  }

  return null;
}

function chainHelpers() {
  return { GENESIS_HASH, linkHash };
}


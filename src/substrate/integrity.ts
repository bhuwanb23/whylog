/**
 * The compliance statement rendered into `DECISIONS.md`.
 *
 * Phrased to be true even when nothing is verified. "No decision in this file has
 * an automated check" is a statement a reader can act on; "compliance: 100%" on an
 * unguarded log is a number that means nothing and reads like a pass.
 */
export function complianceStatement(state: GraphState): string {
  const report = compliance(state);
  const cov = coverage(state);

  if (report.accepted === 0) {
    return `No decision in this file has an automated check yet. ${cov.unguardedButVerifiable} could have one.`;
  }

  const parts = [
    `${report.passing}/${report.accepted} automated checks pass (${Math.round(report.compliance * 100)}%).`,
    `${Math.round(cov.verifiableCoverage * 100)}% of live decisions are covered by a check.`,
  ];

  if (report.failing > 0) {
    parts.push(
      `${report.failing} check${report.failing === 1 ? "" : "s"} failing: the codebase no longer matches the decision${report.failing === 1 ? "" : "s"} below.`,
    );
  }
  if (cov.unverifiableByNature > 0) {
    parts.push(
      `${cov.unverifiableByNature} decision${cov.unverifiableByNature === 1 ? "" : "s"} rest only on intent-based premises and cannot be checked mechanically.`,
    );
  }

  return parts.join(" ");
}

/** The premises a reader should re-check first: world-observable, load-bearing,
 *  and unverified. This is the actionable half of the stamp. */
export function premisesToRecheck(
  state: GraphState,
  limit = 5,
): readonly { premiseId: string; text: string; decisions: number }[] {
  const out: { premiseId: string; text: string; decisions: number }[] = [];

  for (const [premiseId, decisionIds] of state.premiseToDecisions) {
    const premise = state.premises.get(premiseId);
    if (!premise) continue;
    if (premise.temporal.invalidFrom !== undefined) continue;
    if (!isWorldObservable(premise.type)) continue;
    out.push({ premiseId, text: premise.text, decisions: decisionIds.length });
  }

  out.sort((a, b) => b.decisions - a.decisions || a.premiseId.localeCompare(b.premiseId));
  return out.slice(0, limit);
}

/**
 * The machine-readable block appended to every export.
 *
 * Wrapped in an HTML comment so it is invisible in rendered Markdown and still
 * greppable by a CI script with nothing but `sed`. Deliberately one JSON object on
 * one line: a multi-line block is a multi-line regex, and the CI check should be
 * writable in a shell one-liner.
 */
export const STAMP_MARKER = "whylog:integrity" as const;

export function renderStampBlock(stamp: IntegrityStamp): string {
  return `<!-- ${STAMP_MARKER} ${JSON.stringify(stamp)} -->`;
}

/** Extract the stamp from a file's text, if present. */
export function parseStampBlock(text: string): IntegrityStamp | null {
  const marker = `<!-- ${STAMP_MARKER} `;
  const start = text.indexOf(marker);
  if (start < 0) return null;

  const from = start + marker.length;
  const end = text.indexOf("-->", from);
  if (end < 0) return null;

  try {
    const parsed = JSON.parse(text.slice(from, end).trim()) as IntegrityStamp;
    if (typeof parsed.headHash !== "string") return null;
    return parsed;
  } catch {
    return null;
  }
}

/** Strip the stamp block, for diffing two exports without the noise of a changed
 *  timestamp and head hash. */
export function stripStampBlock(text: string): string {
  const marker = `<!-- ${STAMP_MARKER} `;
  const start = text.indexOf(marker);
  if (start < 0) return text;
  const end = text.indexOf("-->", start);
  if (end < 0) return text;
  return (text.slice(0, start) + text.slice(end + 3)).trim();
}

